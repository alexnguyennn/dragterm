#!/bin/sh
# Build dragterm and install it as app bundles.
#
# A bare Mach-O executable has no bundle for LaunchServices to classify, so it comes up as
# NSApplicationActivationPolicyProhibited and can never be activated. macOS 26 will hand
# such a process pointer motion but never a click, so a drag can never start. It needs a
# bundle.
#
# Two bundles are installed, because they differ in a way that matters for dragging:
#
#   drag           LSUIElement agent. No Dock tile, but LaunchServices will not make an
#                  agent the active application, and a drag from an inactive app is never
#                  negotiated with a destination.
#   drag-regular   Ordinary app. Gets a Dock tile while it runs, but it can become active,
#                  which is what a drag session needs in order to highlight a destination
#                  and see the mouse up.
#
# Both must be wrappers that exec the in-bundle path rather than symlinks to it: the main
# bundle is derived from the path the binary was exec'd by, so a symlink loses the bundle.
#
# Overridable: DEVELOPER_DIR, BINDIR, PREFIX.
set -eu

export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode-26.6.0.app/Contents/Developer}"

root="$(cd "$(dirname "$0")" && pwd)"
build="$root/build"
prefix="${PREFIX:-${XDG_DATA_HOME:-$HOME/.local/share}/dragterm}"
bin="${BINDIR:-$HOME/.local/bin}"

xcodebuild -project "$root/dragterm.xcodeproj" -scheme dragterm -configuration Release \
	-destination 'platform=macOS,arch=arm64' -derivedDataPath "$build" \
	CODE_SIGN_IDENTITY=- CODE_SIGNING_REQUIRED=NO -quiet

binary="$build/Build/Products/Release/drag"

# Xcode's processed Info.plist already has the $(...) build settings substituted.
processed="$(find "$build/Build/Intermediates.noindex" -name Processed-Info.plist -print -quit)"

install_bundle() {
	name="$1"
	agent="$2"
	bundle_id="$3"
	app="$prefix/$name.app"

	rm -rf "$app"
	mkdir -p "$app/Contents/MacOS"
	cp "$binary" "$app/Contents/MacOS/drag"
	cp "$processed" "$app/Contents/Info.plist"

	plutil -insert CFBundleExecutable -string drag "$app/Contents/Info.plist"
	plutil -insert CFBundlePackageType -string APPL "$app/Contents/Info.plist"
	plutil -insert LSUIElement -bool "$agent" "$app/Contents/Info.plist"

	# The two bundles must not share a CFBundleIdentifier: LaunchServices resolves the id, so
	# a duplicate makes the regular bundle inherit the agent's registration.
	plutil -replace CFBundleIdentifier -string "$bundle_id" "$app/Contents/Info.plist"

	codesign --force --sign - --options runtime --entitlements "$root/drag.entitlements" "$app"

	# Unlink first: writing through a pre-existing symlink into the bundle would overwrite
	# the real binary with the wrapper, leaving a script that execs itself forever.
	rm -f "$bin/$name"
	printf '#!/bin/sh\nexec "%s/Contents/MacOS/drag" "$@"\n' "$app" > "$bin/$name"
	chmod +x "$bin/$name"

	echo "installed $app"
	echo "     -> $bin/$name"
}

mkdir -p "$bin"

install_bundle drag yes org.derailer.dragterm
install_bundle drag-regular no org.derailer.dragterm.regular

# drag-open: hand the launch to LaunchServices instead of exec'ing the binary ourselves.
#
# A process exec'd from a shell gets no application record at all - `lsappinfo info -pid`
# reports a NULL activation policy and the process is missing from `lsappinfo list` - and
# without that record there is no drag-server registration, so the drag session is never
# advertised to other applications: the drag image is drawn and moved by us alone, no
# destination ever highlights, and the button release goes to whichever application is
# frontmost. Launching through LaunchServices is the only way to obtain that record.
#
# The cost: stdio is detached, so the log goes to a file, and cancel is Escape/q as a key
# event rather than a byte on the terminal's stdin.
app="$prefix/drag-regular.app"
log="$prefix/drag-open.log"

# The wrapper is written from a quoted heredoc and then patched, so that none of its own $
# handling has to survive two levels of expansion.
cat > "$bin/drag-open" <<'EOF'
#!/bin/sh
# Generated by install.sh - do not edit.
if [ $# -eq 0 ]; then
	echo "Usage: drag-open <files>" >&2
	exit 1
fi

# Launches that lose the race are left stopped at _dyld_start and never exit on their own, so
# every attempt has to reap its own corpses. Anything of ours that is stopped is a failed
# attempt: a running drag is never stopped, it exits when the session ends.
reap() {
	for pid in $(pgrep -f "@APP@/Contents/MacOS/drag"); do
		case "$(ps -o stat= -p "$pid" 2>/dev/null)" in
			T*) kill -9 "$pid" 2>/dev/null ;;
		esac
	done
}

reap
: > "@LOG@"
echo "drag: launching via LaunchServices; log: @LOG@" >&2

open -n -W "@APP@" --stderr "@LOG@" --args "$@"
status=$?

sleep 1
reap

exit $status
EOF

sed -e "s|@APP@|$app|g" -e "s|@LOG@|$log|g" "$bin/drag-open" > "$bin/drag-open.tmp"
mv "$bin/drag-open.tmp" "$bin/drag-open"
chmod +x "$bin/drag-open"

echo "installed     $bin/drag-open"
